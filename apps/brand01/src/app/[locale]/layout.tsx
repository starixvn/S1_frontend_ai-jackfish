import { ToastContainer } from 'react-toastify'
import 'react-toastify/dist/ReactToastify.css'
import 'swiper/css/bundle'
import { useServerTranslation } from '../../i18n'
import { fallbackLng, languages } from '../../i18n/settings'
import '../../style/global.css'

export async function generateMetadata({
	params: { locale },
}: {
	params: {
		locale: string
	}
}) {
	if (languages.indexOf(locale) < 0) locale = fallbackLng
	const { t } = await useServerTranslation(locale)
	return {
		title: t(`${process.env.NEXT_PUBLIC_SITE_NAME}`),
		description: 'Generated by create next app',
		icons: {
			icon: [
				{
					url: `${process.env.NEXT_PUBLIC_IMAGE_HOST}/img/favicon.ico`,
					href: `${process.env.NEXT_PUBLIC_IMAGE_HOST}/img/favicon.ico`,
				},
			],
		},
	}
}

export default function RootLayout({
	children,
	params: { locale },
}: {
	children: React.ReactNode
	params: {
		locale: string
	}
}) {
	return (
		<html lang={locale}>
			<body className='mx-auto bg-neutral-500'>
				{children}
				<ToastContainer />
			</body>
		</html>
	)
}
