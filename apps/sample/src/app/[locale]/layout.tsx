import { Inter } from 'next/font/google'

import '../../style/global.css'
import { languages, fallbackLng } from '../../i18n/settings'
import { useServerTranslation } from '../../i18n'

const inter = Inter({ subsets: ['latin'] })

export async function generateMetadata({
	params: { locale },
}: {
	params: {
		locale: string
	}
}) {
	if (languages.indexOf(locale) < 0) locale = fallbackLng
	const { t } = await useServerTranslation(locale)
	return {
		title: t('Sample'),
		description: 'Generated by create next app',
	}
}

export default function RootLayout({
	children,
	params: { locale },
}: {
	children: React.ReactNode
	params: {
		locale: string
	}
}) {
	return (
		<html lang={locale}>
			<body className={`${inter.className} flex flex-col h-screen`}>
				<header className='bg-secondary p-4 text-lg text-left'>
					<p className='text-primary'>Header Block</p>
				</header>
				<main className='flex-grow'>{children}</main>
				<footer className='bg-secondary  p-4 text-center'>
					<p className='text-primary'>Footer Content</p>
				</footer>
			</body>
		</html>
	)
}
